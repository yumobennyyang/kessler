import { fal } from "@fal-ai/client";
import { promises as fs } from "fs";
import path from "path";
import { fileURLToPath } from "url";
import sharp from "sharp";

const __dirname = path.dirname(fileURLToPath(import.meta.url));

// Load .env.local manually
const envPath = path.join(__dirname, "../.env.local");
const envContent = await fs.readFile(envPath, "utf8");
for (const line of envContent.split("\n")) {
    const match = line.match(/^([^#=]+)=(.*)$/);
    if (match) process.env[match[1].trim()] = match[2].trim();
}

fal.config({ credentials: () => process.env.FAL_KEY ?? "" });

const COUNT = 30;
const refsDir = path.join(__dirname, "../public/references_2.0");
const thumbsDir = path.join(refsDir, "thumbs");
await fs.mkdir(thumbsDir, { recursive: true });

const UPLOAD_MAX_EDGE = 2048;
const THUMB_MAX_EDGE = 512;

const urls = {};

for (let n = 1; n <= COUNT; n++) {
    const src = path.join(refsDir, `${n}.png`);
    const buf = await fs.readFile(src);

    // Thumbnail for the picker grid
    await sharp(buf)
        .resize(THUMB_MAX_EDGE, THUMB_MAX_EDGE, { fit: "inside", withoutEnlargement: true })
        .jpeg({ quality: 80 })
        .toFile(path.join(thumbsDir, `${n}.jpg`));

    // Compressed copy for the model — full PNGs run up to 18MB
    const uploadBuf = await sharp(buf)
        .resize(UPLOAD_MAX_EDGE, UPLOAD_MAX_EDGE, { fit: "inside", withoutEnlargement: true })
        .jpeg({ quality: 90 })
        .toBuffer();

    const file = new File([uploadBuf], `ref2-${n}.jpg`, { type: "image/jpeg" });
    const url = await fal.storage.upload(file);
    urls[n] = url;
    console.log(`${n}: ${url} (${(uploadBuf.length / 1024).toFixed(0)}KB)`);
}

const ts = `// Generated by scripts/upload-refs2.mjs — do not edit by hand.
// fal.media URLs for the 30 collage references in public/references_2.0.

export const STUDIO_REF_COUNT = ${COUNT};

export const STUDIO_REF_URLS: Record<number, string> = {
${Object.entries(urls).map(([n, u]) => `    ${n}: "${u}",`).join("\n")}
};
`;

await fs.writeFile(path.join(__dirname, "../src/lib/studioRefs.ts"), ts);
console.log("\nWrote src/lib/studioRefs.ts");
